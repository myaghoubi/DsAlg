const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

function render() {
  const cur = String(self.APP_VERSION);
  return '<div class="cl"><div class="cl-intro">فهرست تغییرات هر نسخه، همراه با درخواست اصلی که آن بروزرسانی را ایجاد کرد. جدیدترین نسخه در بالاست.</div>' +
    LOG.map((e) => '<section class="card cl-item' + (e.v === cur ? ' cur' : '') + '">' +
      '<div class="cl-head"><span class="cl-v">' + esc(e.v) + '</span><span class="cl-t">' + esc(e.title) + '</span>' +
      (e.v === cur ? '<span class="cl-now">نسخه‌ی فعلی</span>' : '') +
      '<span class="cl-tags">' + e.tags.map((t) => '<span>' + esc(t) + '</span>').join('') + '</span></div>' +
      '<div class="cl-req"><b>درخواست:</b> ' + esc(e.req) + '</div>' +
      '<ul>' + e.items.map((i) => '<li>' + esc(i) + '</li>').join('') + '</ul>' +
      '<div class="cl-files">فایل‌ها:<code>' + e.files.map(esc).join(' ، ') + '</code></div></section>').join('') + '</div>';
}

